-- Добавляет анонимный лайк-счётчик к уже существующей боевой таблице news.
-- schema.sql описывает колонку сразу в CREATE TABLE IF NOT EXISTS — для
-- чистой установки этот файл не нужен, только для базы, где news уже создана
-- без неё. Выполняется вручную на проде (контроллер), Claude базу не трогает.

-- DEFAULT 0, а не NULL: счётчик обязан быть числом с первого же поста —
-- api/news_like.php читает likes арифметически (likes + :inc), NULL там дал
-- бы NULL на выходе арифметики, а не 0. Существующие посты получают 0 лайков
-- сразу же, без отдельного шага переноса данных (в отличие от миграции
-- 2026-08-18-image-customisation.sql, где старому пресету было что
-- переносить).
ALTER TABLE news
  ADD COLUMN likes INT UNSIGNED NOT NULL DEFAULT 0 AFTER published_at;
