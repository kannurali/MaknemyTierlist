-- --------------------------------------------------------------------------
--  Что человек хочет получать
-- --------------------------------------------------------------------------
-- Одна строка — один аккаунт сайта, и только если человек что-то
-- переключал: строки нет — всё включено.
--
-- Отдельно от tg_links намеренно: переподключение Telegram пересоздаёт
-- привязку, а выбор человека должен её пережить.
CREATE TABLE IF NOT EXISTS tg_prefs (
  user_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
  prices  TINYINT(1)      NOT NULL DEFAULT 1,
  news    TINYINT(1)      NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
