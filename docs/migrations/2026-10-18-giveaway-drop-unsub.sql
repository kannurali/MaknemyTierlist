-- Галочка «Снимать участие у отписавшихся» у каждого розыгрыша. Запускать
-- один раз на боевой базе, после 2026-10-14-giveaways.sql.
--
-- drop_unsub = 1 (по умолчанию, так у всех уже созданных) — как было: вышел
-- из канала условий — участие снято, бот пишет «вы отписались и больше не
-- участвуете», на итогах подписку перепроверяют.
-- drop_unsub = 0 — подписку бот проверяет только при участии; отписаться
-- потом можно, участие и шанс на приз остаются.
--
-- Пока колонки нет, отписка снимает участие везде, а снять галочку админка
-- не даёт и просит эту миграцию.

ALTER TABLE giveaways ADD COLUMN drop_unsub TINYINT(1) NOT NULL DEFAULT 1 AFTER conds_json;
