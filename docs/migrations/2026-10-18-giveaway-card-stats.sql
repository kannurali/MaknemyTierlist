-- Показы и переходы карточек розыгрыша на страницах сайта. Запускать один
-- раз на боевой базе, после 2026-10-14-giveaways.sql.
--
-- Пока таблицы нет, карточки показываются как обычно, а api/gw_stat.php
-- молча ничего не записывает: в отчёте /admin/giveaways у мест будут нули
-- показов и переходов, участия по местам считаются и без неё (src участника).

-- --------------------------------------------------------------------------
--  Карточки розыгрыша по местам
-- --------------------------------------------------------------------------
-- place — где стояла карточка:
--   tier  — тирлист, над первой полосой;
--   tmid  — тирлист, в середине, под рекламной полосой;
--   trade — лента трейдов, после второго объявления;
--   calc  — калькулятор, под итогом сравнения;
--   stock — сток, над карточками дилеров;
--   news  — новости, над лентой.
-- views  — сколько раз карточка была видна (половиной площади, от секунды),
--          не больше одного раза на место за просмотр страницы;
-- clicks — сколько раз по ней нажали.
-- Участия по местам — в giveaway_entries.src ('c-' + place).
CREATE TABLE IF NOT EXISTS gw_card_stats (
  giveaway_id INT UNSIGNED NOT NULL,
  place       VARCHAR(8)   NOT NULL,
  views       INT UNSIGNED NOT NULL DEFAULT 0,
  clicks      INT UNSIGNED NOT NULL DEFAULT 0,
  PRIMARY KEY (giveaway_id, place)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
