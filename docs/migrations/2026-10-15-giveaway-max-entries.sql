-- max_entries — сколько человек может участвовать; 0 — без лимита. Кто занял
-- последнее место, тот и закрывает приём: время конца становится «сейчас», и
-- дальше всё как у розыгрыша, у которого вышло время, — он ждёт кнопки
-- «Разыграть» в админке. Время конца по-прежнему обязательно: что наступит
-- раньше, то и закроет приём.
--
-- Пока колонки нет, лимитов нет ни у кого, а админка не даёт его поставить и
-- просит миграцию.

ALTER TABLE giveaways ADD COLUMN max_entries INT UNSIGNED NOT NULL DEFAULT 0 AFTER conds_json;
