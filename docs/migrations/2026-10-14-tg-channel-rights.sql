-- Права бота в каналах розыгрышей. Запускать один раз на боевой базе, после
-- 2026-10-14-giveaways.sql.
--
-- Бот годится для условий розыгрыша, только если он админ канала с правами
-- «Отправка публикаций», «Публикация историй», «Блокировка пользователей»,
-- «Добавление подписчиков» и «Доступ к сообщениям канала» (TG_CHANNEL_RIGHTS
-- в api/lib/telegram.php). Без них is_admin = 0, а в missing — каких прав не
-- хватает, через запятую: can_post_stories,can_invite_users. Пусто — всё есть
-- (или бот вовсе не админ).
--
-- Пока колонки нет, проверка прав всё равно работает, только админка не
-- называет недостающие права.
--
-- После миграции: /admin/support → «Подключить вебхук» (бот запомнит права
-- по умолчанию), потом /admin/giveaways → «Обновить» у каждого канала —
-- каналы, добавленные раньше, ещё не проверены.

ALTER TABLE tg_channels ADD COLUMN missing VARCHAR(255) NOT NULL DEFAULT '' AFTER is_admin;
