-- Присутствие пользователя. Запускать один раз на боевой базе, ПОСЛЕ schema.sql.
--
-- Зачем отдельная колонка, а не last_login_at. Вход пишется РОВНО ОДИН РАЗ —
-- в момент возврата с roblox.com (roblox_touch_user), — а сессия живёт долго:
-- человек логинится раз и потом неделю ходит по сайту. Поэтому «в сети»,
-- посчитанное от времени входа, у активного посетителя гаснет через пять
-- минут после логина и больше не загорается никогда. Индикатор на странице
-- профиля при этом честно показывал бы «не в сети» человеку, который прямо
-- сейчас эту страницу и читает.
--
-- Обновляет колонку api/session.php — запрос, который шапка делает на каждой
-- странице у каждого вошедшего. Своего эндпоинта и своего запроса для отметки
-- не нужно: соединение там уже открыто, а строка пользователя уже прочитана.
-- Порог — не чаще раза в минуту (ROBLOX_SEEN_THROTTLE в api/lib/roblox_oauth.php):
-- без него это была бы запись в users на каждую загрузку страницы, а точность
-- индикатора всё равно меряется минутами.
--
-- Точность у отметки ровно такая, какую даёт загрузка страницы: тот, кто пять
-- минут читает одну длинную новость, успеет «уйти». Непрерывное присутствие
-- потребовало бы опроса или сокета — цена, несоразмерная двум точкам в
-- карточке.

ALTER TABLE users
  ADD COLUMN last_seen_at BIGINT UNSIGNED NOT NULL DEFAULT 0;

-- Переносим то, что известно на сегодня: до этой миграции единственным следом
-- присутствия был вход.
--
-- WHERE last_seen_at = 0 — чтобы повторный запуск не откатывал уже
-- проставленные отметки на время входа. Миграции здесь выполняются руками, а
-- рука повторяет.
--
-- Строго говоря, без переноса код и так не сломается: profile_card() берёт
-- позднее из last_seen_at и last_login_at. Перенос делает состояние базы
-- честным само по себе, не полагаясь на то, что читатель угадает правило.
UPDATE users SET last_seen_at = last_login_at WHERE last_seen_at = 0;
