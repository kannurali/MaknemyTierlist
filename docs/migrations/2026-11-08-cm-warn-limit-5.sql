-- Чат-менеджер: лимит варнов по умолчанию 3 → 5 (решение владельца 08.11.2026).
-- Новым чатам 5 даёт сам код (CM_DEFAULTS в api/lib/cm/db.php), а у уже
-- стоящих в cm_chats.settings записан прежний лимит 3: бот сохраняет настройки
-- целиком, в том числе при отметке «чат Макнеми». Этот запрос меняет 3 на 5;
-- лимит, который модератор поставил другим числом, не трогается. Без него в
-- старых чатах то же делает команда «варны лимит 5» (ранг 3).
-- Запускать один раз, порядок с другими миграциями не важен.

UPDATE cm_chats
   SET settings = REPLACE(settings, '"warns":{"limit":3,', '"warns":{"limit":5,')
 WHERE settings LIKE '%"warns":{"limit":3,%';
