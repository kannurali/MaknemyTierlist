-- Отписка от каналов условий. Запускать один раз на боевой базе, после
-- 2026-10-14-giveaways.sql.
--
-- giveaways.drop_unsub — галочка «Снимать участие у отписавшихся» у каждого
-- розыгрыша. 1 (по умолчанию, так у всех уже созданных): вышел из канала
-- условий — участие снято, бот пишет «вы отписались и больше не
-- участвуете», на итогах подписку перепроверяют. 0 — подписку бот проверяет
-- только при участии; отписаться потом можно, участие и шанс на приз
-- остаются.
--
-- giveaway_entries.left_at — когда участие снято за отписку, 0 — участвует.
-- Строка не удаляется: это след того, что человек вступал подписанным. В
-- число участников и в розыгрыш она не входит; подписался снова и нажал
-- «Участвовать» — left_at снова 0.
-- giveaway_entries.checked_at — когда бот последний раз сам перепроверил
-- подписку (getChatMember после ответов /api/giveaways.php). Первыми
-- проверяются те, у кого он меньше; индекс — для этой очереди.
--
-- Пока колонок нет, отписка удаляет строку участника (как раньше), в фоне
-- подписку никто не перепроверяет, а снять галочку админка не даёт и просит
-- эту миграцию.

ALTER TABLE giveaways ADD COLUMN drop_unsub TINYINT(1) NOT NULL DEFAULT 1 AFTER conds_json;

ALTER TABLE giveaway_entries
  ADD COLUMN left_at    BIGINT UNSIGNED NOT NULL DEFAULT 0 AFTER src,
  ADD COLUMN checked_at BIGINT UNSIGNED NOT NULL DEFAULT 0 AFTER left_at,
  ADD KEY idx_check (left_at, checked_at);
