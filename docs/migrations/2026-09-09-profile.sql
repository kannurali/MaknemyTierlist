-- Своей таблицы пользователей профиль не заводит: users уже есть (её создаёт
-- schema.sql вместе с входом через Roblox), ключ там roblox_id. Ник, аватар и
-- время последнего входа берутся оттуда же, что и в шапке сайта — второй
-- список людей означал бы два ответа на вопрос «кто это».
--
-- Колонки status тут нет и не будет: её пришлось бы кому-то проставлять и
-- вовремя сбрасывать, а last_login_at уже пишется при каждом входе
-- (roblox_touch_user) и врать не может. «В сети» вычисляется из него —
-- см. PROFILE_ONLINE_WINDOW в api/lib/profile.php.
--
-- Репутация (likes/dislikes) приезжает НЕ отсюда, а миграцией чатов: отзывы
-- ставятся по итогам переписки, и колонки заводит тот, кто их пишет. Профиль
-- их только показывает и переживает их отсутствие — до выполнения миграции
-- чатов оба счётчика читаются как ноль (см. profile_card).

-- --------------------------------------------------------------------------
--  «О себе»
-- --------------------------------------------------------------------------
-- Единственная колонка, которую заводит профиль: текст пишет сам человек на
-- своей странице (POST /api/profile-about.php), и хранить его больше негде.
--
-- VARCHAR(280), а не TEXT: предел показан в интерфейсе счётчиком символов, и
-- ровно он же стоит в PROFILE_ABOUT_MAX. TEXT позволил бы положить мегабайт
-- в обход клиентской проверки и растянуть карточку на весь экран.
--
-- NULL по умолчанию — это «человек ничего не написал». Пустая строка значила
-- бы то же самое двумя разными способами, поэтому profile_about_save()
-- кладёт именно NULL, когда поле очистили.
ALTER TABLE users
  ADD COLUMN about VARCHAR(280) NULL DEFAULT NULL;
