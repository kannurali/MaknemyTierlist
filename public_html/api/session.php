<?php
require_once __DIR__ . '/_bootstrap.php';
require_once __DIR__ . '/lib/roblox_oauth.php';

/**
 * Кто сейчас на сайте. Одна ручка на всё состояние входа:
 *   admin  — вошедший через Roblox есть в admin_ids (вся панель);
 *   moderator — есть в admin_ids или moderator_ids (обращения). По этим
 *            двум шапка решает, какую ссылку на панель дать в меню;
 *   user   — вошедший через Roblox или null;
 *   roblox — заведено ли вообще приложение в Roblox. По нему шапка решает,
 *            показывать кнопку входа или оставить прежнюю заглушку: пока
 *            client_id не прописан, кнопка вела бы на 503.
 *   roblox_public — открыт ли вход всем. Пока нет, кнопку видят только
 *            пришедшие по ссылке с ?signin (см. roblox_login_public()).
 *
 * База открывается через $pdo() и только когда в сессии есть вошедший.
 * Ручку теперь дёргает шапка на каждой странице сайта, а не одна админка,
 * и платить соединением с MySQL за анонимного посетителя незачем.
 *
 * Раз уж ручку дёргает каждая страница у каждого вошедшего — здесь же
 * отмечается присутствие (roblox_touch_seen, не чаще раза в минуту). Своего
 * запроса и своего эндпоинта для этого не нужно: соединение уже открыто, а
 * строка пользователя уже прочитана.
 *
 * Да, это GET, который пишет, — в обход правила require_post. Правило стоит
 * против изменений, которые чужая страница может вызвать в браузере
 * посетителя; здесь такой вызов даёт ровно одно: человек полминуты выглядит
 * «в сети», не будучи на сайте. Ни данных, ни доступа это не меняет, а частоту
 * записи держит тот же порог. Требовать POST значило бы сломать кеширование
 * ручки и завести второй запрос там, где хватает нулевого.
 *
 * $now отдельным параметром, а не time() внутри: иначе порог отметки нечем
 * проверить, кроме как ждать минуту в тесте.
 */
function handle_session(callable $pdo, array $session, array $cfg, ?int $now = null): array {
    $user = null;
    $uid  = (string)($session['user_id'] ?? '');
    if ($uid !== '') {
        try {
            $conn = $pdo();
            $user = roblox_load_user($conn, $uid);
            if ($user !== null) {
                roblox_touch_seen($conn, $user, $now ?? time());
            }
        } catch (PDOException $e) {
            // Таблицы users нет (не выполнен schema.sql) — считаем, что никто
            // не вошёл. Сайт от этого не ломается, шапка просто покажет
            // кнопку входа.
            $user = null;
        }
    }
    // seen из ответа убираем: шапке он не нужен, а лишнее поле в JSON — это
    // лишнее обещание. Присутствие показывает профиль, и берёт он его из базы.
    if ($user !== null) { unset($user['seen']); }

    $role = site_role($session, $cfg);
    return [
        'admin'         => $role === 'admin',
        'moderator'     => $role !== '',
        'user'          => $user,
        'roblox'        => roblox_oauth_enabled($cfg),
        'roblox_public' => roblox_login_public($cfg),
    ];
}

if (!defined('TESTING')) {
    header('Cache-Control: no-store');
    // Анонимному посетителю сессия не заводится: раньше каждый первый заход
    // на любую страницу оставлял на сервере файл сессии и получал куку, хотя
    // хранить в ней было нечего. Сессию заводят вход через Roblox и вход в
    // админку.
    $session = resume_site_session() ? $_SESSION : [];
    json_out(handle_session('db', $session, app_config()), 200);
}
