// Счётчик статистики — один на все публичные страницы сайта.
//
// Имя файла и функций осталось от Яндекс Метрики. С 2026-10-20 Метрики на
// сайте нет, решение владельца: с 13.10 её кабинет перестал показывать
// статистику, базовый подсчёт с того же дня дублировал Google Analytics
// (api/lib/google_analytics.php), а Вебвизором и картами кликов, ради которых
// её стоило держать, не пользовались. Функции не переименованы
// намеренно: их зовут полтора десятка страниц и открытые PR с новыми
// страницами, и после переименования любая такая страница падала бы на
// неизвестной функции.
//
// Раньше код счётчика лежал прямо в index.php, и только там. В статистику
// из-за этого попадал один тирлист: главная, калькулятор и лента новостей не
// считались вовсе, хотя в шапке стоят равноправными разделами. По отчётам
// такое не видно в принципе — счётчик показывает ровно те страницы, до
// которых доехал, и раздел без счётчика выглядит как «туда не ходят», а не
// как «там нечем считать».
//
// Общего <head> у страниц нет — каждая пишет свой (см. home.php, index.php,
// calculator.php, news.php), поэтому разметка отдаётся функцией, а не
// include-ом шаблона: место вставки остаётся за страницей, а сам код счётчика
// живёт в единственном экземпляре.

require_once __DIR__ . '/google_analytics.php';

function metrika_counter_html(): string {
    return ga_counter_html();
}

// Убирает счётчик из уже отрендеренной публичной страницы.
//
// Нужно админке: /admin и /admin/news не хранят копию вёрстки, а исполняют
// index.php и news.php целиком (см. admin_render_public_page()), поэтому
// счётчик приезжает к ним вместе со всей разметкой. Свои же клики и визиты
// редактора в статистике сайта — мусор, который к тому же не отфильтровать
// задним числом.
//
// Вызов живёт в admin_render_public_page(), а не в самих admin*.php: раньше
// вырезание стояло только в admin.php, и когда лента новостей получила свою
// админку, /admin/news осталась бы со счётчиком — ровно тот класс ошибки,
// который повторяется при каждой новой админ-странице.
//
// На месте блока остаётся след: без него пропажу счётчика не отличить от
// того, что его на странице и не было.
function metrika_strip(string $html): string {
    $out = preg_replace(
        '~<!-- Google Analytics -->.*?<!-- /Google Analytics -->~su',
        '<!-- Счётчик вырезан: админку в статистику сайта не считаем. -->',
        $html,
        1
    );
    // preg_replace возвращает null на сбое (например, backtrack limit на
    // очень длинной странице). Отдать null вместо страницы — уронить админку
    // целиком; лучше вернуть разметку как есть.
    return $out ?? $html;
}
