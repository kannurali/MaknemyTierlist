<?php
// Счётчики статистики — один вызов на все публичные страницы сайта:
// Яндекс Метрика и Google Analytics (api/lib/google_analytics.php).
//
// История. 2026-10-13 кабинет Метрики перестал показывать статистику, и рядом
// встал GA. 2026-10-20 Метрику сняли совсем (GA дублировал базовый подсчёт, а
// Вебвизором не пользовались). 2026-11-17 её вернули по решению владельца:
// впереди Рекламная сеть Яндекса, а РСЯ считает доход и качество трафика по
// счётчику Метрики. Номер прежний — 111127188: новый счётчик начал бы историю
// и Вебвизор с нуля.
//
// Раньше код счётчика лежал прямо в index.php, и только там. В статистику
// из-за этого попадал один тирлист: главная, калькулятор и лента новостей не
// считались вовсе, хотя в шапке стоят равноправными разделами. По отчётам
// такое не видно в принципе — счётчик показывает ровно те страницы, до
// которых доехал, и раздел без счётчика выглядит как «туда не ходят», а не
// как «там нечем считать».
//
// Общего <head> у страниц нет — каждая пишет свой (см. home.php, index.php,
// calculator.php, news.php), поэтому разметка отдаётся функцией, а не
// include-ом шаблона: место вставки остаётся за страницей, а сам код счётчиков
// живёт в единственном экземпляре. Страницы второго сайта (скин vx) эту
// функцию не зовут: счётчики только у maknemy.com.

require_once __DIR__ . '/google_analytics.php';

// Номер счётчика. Этот же номер зашит в js/metrika.js (загрузка и init) и в
// js/promo.js — там он уходит в ym(..., 'reachGoal', ...) из PROMO.goal() для
// кликов по рекламе, и общей константы у PHP с браузерным кодом нет.
// Расхождение ловит tests/metrika_test.php.
const METRIKA_ID = 111127188;

// Комментарии-маркеры вокруг блока — часть контракта, а не оформление: по ним
// metrika_strip() вырезает счётчик из админских страниц. Уберёшь их —
// собственные клики и Вебвизор редактора начнут молча попадать в статистику
// сайта.
//
// Перевод строки в конце дописывается отдельно, потому что PHP съедает ровно
// один перевод сразу после закрывающего тега. Без него закрывающий маркер и
// следующий блок склеились бы в одну строку.
//
// Код счётчика — во внешнем js/metrika.js, а не прямо в разметке: сайт
// отдаёт Content-Security-Policy без 'unsafe-inline' в script-src (.htaccess),
// и встроенный скрипт браузер бы не исполнил. Этот способ Метрика описывает
// сама («Установка счетчика на сайт с CSP»). async — чтобы не держать
// разбор <head>: код и сам грузит tag.js асинхронно, а цели в PROMO.goal()
// зовут ym только после проверки typeof ym === "function".
//
// Блок GA идёт следом — новой странице по-прежнему хватает одного вызова.
function metrika_counter_html(): string {
    $id = METRIKA_ID;
    $block = <<<HTML
<!-- Yandex.Metrika counter -->
<script src="/js/metrika.js?v=2" async></script>
<noscript><div><img src="https://mc.yandex.ru/watch/{$id}" style="position:absolute; left:-9999px;" alt="" /></div></noscript>
<!-- /Yandex.Metrika counter -->
HTML;
    return $block . "\n" . ga_counter_html();
}

// Убирает счётчики (Метрику и GA) из уже отрендеренной публичной страницы.
//
// Нужно админке: /admin и /admin/news не хранят копию вёрстки, а исполняют
// index.php и news.php целиком (см. admin_render_public_page()), поэтому
// счётчики приезжают к ним вместе со всей разметкой. Свои же клики, прокрутки
// и записи Вебвизора в статистике сайта — мусор, который к тому же не
// отфильтровать задним числом.
//
// Вызов живёт в admin_render_public_page(), а не в самих admin*.php: раньше
// вырезание стояло только в admin.php, и когда лента новостей получила свою
// админку, /admin/news осталась бы со счётчиком — ровно тот класс ошибки,
// который повторяется при каждой новой админ-странице.
//
// На месте Метрики остаётся след: без него пропажу счётчика не отличить от
// того, что его на странице и не было. Блок GA вырезается вместе со своим
// переводом строки, чтобы след и </head> не разъехались пустой строкой.
function metrika_strip(string $html): string {
    $out = preg_replace(
        ['~<!-- Yandex\.Metrika counter -->.*?<!-- /Yandex\.Metrika counter -->~su',
         '~<!-- Google Analytics -->.*?<!-- /Google Analytics -->\n?~su'],
        ['<!-- Счётчики вырезаны: админку в статистику сайта не считаем. -->', ''],
        $html,
        1
    );
    // preg_replace возвращает null на сбое (например, backtrack limit на
    // очень длинной странице). Отдать null вместо страницы — уронить админку
    // целиком; лучше вернуть разметку как есть.
    return $out ?? $html;
}
