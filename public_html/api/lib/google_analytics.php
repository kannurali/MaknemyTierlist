<?php
// Счётчик Google Analytics 4 — единственная статистика сайта.
//
// 2026-10-13 GA встал рядом с Яндекс Метрикой, когда её кабинет перестал
// показывать статистику; 2026-10-20 Метрику сняли совсем (почему — в
// api/lib/metrika.php).
//
// Подключается не сам по себе, а изнутри metrika_counter_html() (см.
// api/lib/metrika.php): каждая публичная страница уже зовёт эту функцию в
// своём <head>, и второй вызов на дюжине страниц было бы легко забыть на
// следующей новой. По той же причине metrika_strip() вырезает из админки
// именно этот блок.

// Measurement ID ресурса GA4 (вида G-XXXXXXXXXX). Пустая строка — счётчик
// выключен: блок не печатается, js/ga.js не грузится. Это же и рубильник,
// если с GA что-то пойдёт не так.
//
// В браузерный код номер не дублируется: js/ga.js берёт его из data-id
// своего тега, а цели (PROMO.goal в js/promo.js) зовут gtag('event', …) без
// номера — они уходят во все настроенные ресурсы.
const GA_ID = 'G-HHT247HRCY';

// Маркеры — контракт с metrika_strip(): по ним блок вырезается из админки.
//
// Код — во внешнем js/ga.js: CSP сайта не пускает встроенные скрипты, а
// стандартный сниппет gtag как раз встроенный. js/ga.js сам ставит gtag.js
// асинхронно и ограничен боевым хостом, чтобы локальные прогоны и превью не
// попадали в статистику (в кабинете GA такой настройки нет).
function ga_counter_html(string $id = GA_ID): string {
    if ($id === '') { return ''; }
    $id = htmlspecialchars($id, ENT_QUOTES);
    $block = <<<HTML
<!-- Google Analytics -->
<script src="/js/ga.js?v=1" data-id="{$id}" async></script>
<!-- /Google Analytics -->
HTML;
    return $block . "\n";
}
