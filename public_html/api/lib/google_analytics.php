<?php
// Счётчик Google Analytics 4 — стоит рядом с Метрикой, а не вместо неё.
//
// 2026-10: кабинет Метрики перестал показывать статистику. Счётчик Метрики
// при этом оставлен: данные он собирает по-прежнему, и если доступ к
// кабинету вернётся, история не прервётся. GA — второй источник, которым
// можно пользоваться уже сейчас.
//
// Подключается не сам по себе, а изнутри metrika_counter_html() (см.
// api/lib/metrika.php): каждая публичная страница уже зовёт эту функцию в
// своём <head>, и второй вызов на дюжине страниц было бы легко забыть на
// следующей новой. По той же причине metrika_strip() вырезает из админки и
// этот блок.

// Measurement ID ресурса GA4 (вида G-XXXXXXXXXX). Пустая строка — счётчик
// выключен: блок не печатается, js/ga.js не грузится. Это же и рубильник,
// если с GA что-то пойдёт не так.
//
// В браузерный код номер не дублируется: js/ga.js берёт его из data-id
// своего тега, а цели (PROMO.goal в js/promo.js) зовут gtag('event', …) без
// номера — они уходят во все настроенные ресурсы.
const GA_ID = 'G-HHT247HRCY';

// Маркеры — контракт с metrika_strip(), как и у блока Метрики.
//
// Код — во внешнем js/ga.js по той же причине, что js/metrika.js: CSP сайта
// не пускает встроенные скрипты, а стандартный сниппет gtag как раз
// встроенный. js/ga.js сам ставит gtag.js асинхронно и ограничен боевым
// хостом, чтобы локальные прогоны и превью не попадали в статистику (у
// Метрики то же самое делает настройка в кабинете, у GA такой нет).
function ga_counter_html(string $id = GA_ID): string {
    if ($id === '') { return ''; }
    $id = htmlspecialchars($id, ENT_QUOTES);
    $block = <<<HTML
<!-- Google Analytics -->
<script src="/js/ga.js?v=1" data-id="{$id}" async></script>
<!-- /Google Analytics -->
HTML;
    return $block . "\n";
}
